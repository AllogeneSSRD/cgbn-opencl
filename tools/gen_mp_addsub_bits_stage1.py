#!/usr/bin/env python3
"""Generate stage1 add/sub bit-width paths under add_mod/ and sub_mod/.
Also writes common/asm_common.inc.cl (shared AMDGCN inline-asm infrastructure)."""

from __future__ import annotations

from pathlib import Path

from mp_asm_block_gen import emit_add_block, emit_c_fix_add, emit_sub_block

ROOT = Path(__file__).resolve().parents[1]
ADD_MOD = ROOT / "kernels/opencl/add_mod"
SUB_MOD = ROOT / "kernels/opencl/sub_mod"
COMMON = ROOT / "kernels/opencl/common"

WIDTHS = (
    (128, 4, 128),
    (192, 6, 192),
    (256, 8, 256),
    (384, 12, 378),
)

HEADER = "// AUTO-GENERATED by tools/gen_mp_addsub_bits_stage1.py - do not edit.\n"


def emit_add_unroll(limbs: int, bits: int) -> str:
    lines = [
        f"static inline void add_mod_unroll_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
        "    ulong carry_add = 0ul;\n",
        "    ulong carry_sub = 1ul;\n",
    ]
    for i in range(limbs):
        lines.append(
            f"    {{\n"
            f"        ulong sum = (ulong)a[{i}] + (ulong)b[{i}] + carry_add;\n"
            f"        carry_add = sum >> 32;\n"
            f"        ulong temp = (ulong)(uint)sum + (ulong)(~N[{i}]) + carry_sub;\n"
            f"        carry_sub = temp >> 32;\n"
            f"        r[{i}] = (uint)temp;\n"
            f"    }}\n"
        )
    lines.append("    if ((carry_add | carry_sub) != 0ul) {\n        return;\n    }\n")
    lines.append("    ulong c = 0ul;\n")
    for i in range(limbs):
        lines.append(
            f"    {{\n"
            f"        ulong s = (ulong)r[{i}] + (ulong)N[{i}] + c;\n"
            f"        r[{i}] = (uint)s;\n"
            f"        c = s >> 32;\n"
            f"    }}\n"
        )
    lines.append("}\n\n")
    return "".join(lines)


def emit_sub_unroll(limbs: int, bits: int) -> str:
    lines = [
        f"static inline int sub_mod_unroll_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
        "    ulong br = 0ul;\n",
    ]
    for i in range(limbs):
        lines.append(
            f"    {{\n"
            f"        ulong av = (ulong)a[{i}];\n"
            f"        ulong bv = (ulong)b[{i}];\n"
            f"        ulong w = av - bv - br;\n"
            f"        r[{i}] = (uint)w;\n"
            f"        br = (av < bv + br) ? 1ul : 0ul;\n"
            f"    }}\n"
        )
    lines.append("    if (br != 0ul) {\n        ulong c = 0ul;\n")
    for i in range(limbs):
        lines.append(
            f"        {{\n"
            f"            ulong s = (ulong)r[{i}] + (ulong)N[{i}] + c;\n"
            f"            r[{i}] = (uint)s;\n"
            f"            c = s >> 32;\n"
            f"        }}\n"
        )
    lines.append("        return 1;\n    }\n    return 0;\n}\n\n")
    return "".join(lines)


def emit_add_asm_body(limbs: int, bits: int) -> str:
    return (
        f"static inline void add_mod_asm_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n"
        f"    uint ca = 0u, cs = 1u;\n"
        f"    asm_fused_block{limbs}_priv(a, b, N, r, ca, cs, &ca, &cs);\n"
        f"}}\n\n"
    )


def emit_sub_asm_body(limbs: int, bits: int) -> str:
    return (
        f"static inline int sub_mod_asm_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n"
        f"    uint br = 0u;\n"
        f"    asm_sub_fused_block{limbs}_priv(a, b, N, r, br, &br);\n"
        f"    return br != 0u ? 1 : 0;\n"
        f"}}\n\n"
    )


def emit_add_asm_wrapper(bits: int) -> str:
    return (
        f"#if defined(__AMDGCN__)\n"
        f"static inline void add_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                       const uint *N, uint limbs) {{\n"
        f"    if (limbs == 16u) {{ add_mod_asm_{bits}b_body(r, a, b, N); }}\n"
        f"    (void)limbs;\n"
        f"}}\n"
        f"#else\n"
        f"static inline void add_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                       const uint *N, uint limbs) {{\n"
        f"    if (limbs == 16u) {{ add_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    (void)limbs;\n"
        f"}}\n"
        f"#endif\n"
    )


def emit_sub_asm_wrapper(bits: int) -> str:
    return (
        f"#if defined(__AMDGCN__)\n"
        f"static inline int sub_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                      const uint *N, uint limbs) {{\n"
        f"    if (limbs == 16u) {{ return sub_mod_asm_{bits}b_body(r, a, b, N); }}\n"
        f"    return 0;\n"
        f"}}\n"
        f"#else\n"
        f"static inline int sub_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                      const uint *N, uint limbs) {{\n"
        f"    if (limbs == 16u) {{ return sub_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    return 0;\n"
        f"}}\n"
        f"#endif\n"
    )


def write_asm_common() -> None:
    """Write shared AMDGCN asm infrastructure with #ifndef guards."""
    lines = [
        HEADER,
        "#if defined(__AMDGCN__)\n\n",
    ]
    # c_fix_add functions for each width
    for _bits, limbs, _max_n in WIDTHS:
        guard = f"ASM_COMMON_C_FIX_ADD_N{limbs}_DEFINED"
        body = emit_c_fix_add(limbs)
        lines.append(f"#ifndef {guard}\n#define {guard}\n{body}#endif\n")
    # add blocks
    for _bits, limbs, _max_n in WIDTHS:
        guard = f"ASM_COMMON_FUSED_BLOCK{limbs}_PRIV_DEFINED"
        body = emit_add_block(limbs, global_addr=False, fix_in_block=True)
        lines.append(f"#ifndef {guard}\n#define {guard}\n{body}#endif\n")
    # sub blocks
    for _bits, limbs, _max_n in WIDTHS:
        guard = f"ASM_COMMON_SUB_FUSED_BLOCK{limbs}_PRIV_DEFINED"
        body = emit_sub_block(limbs, global_addr=False, fix_in_block=True)
        lines.append(f"#ifndef {guard}\n#define {guard}\n{body}#endif\n")
    lines.append("#endif // __AMDGCN__\n")
    path = COMMON / "asm_common.inc.cl"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(lines), encoding="utf-8")
    print(f"Wrote {path}")


def write_add_unroll(bits: int, body: str) -> None:
    path = ADD_MOD / f"add_mod_unroll_{bits}b.cl"
    wrapper = (
        f"static inline void add_mod_unroll_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                          const uint *N, uint limbs) {{\n"
        f"    if (limbs == 16u) {{ add_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    (void)limbs;\n"
        f"}}\n"
    )
    path.write_text(f"{HEADER}{body}{wrapper}", encoding="utf-8")
    print(f"Wrote {path}")


def write_sub_unroll(bits: int, body: str) -> None:
    path = SUB_MOD / f"sub_mod_unroll_{bits}b.cl"
    wrapper = (
        f"static inline int sub_mod_unroll_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                         const uint *N, uint limbs) {{\n"
        f"    if (limbs == 16u) {{ return sub_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    return 0;\n"
        f"}}\n"
    )
    path.write_text(f"{HEADER}{body}{wrapper}", encoding="utf-8")
    print(f"Wrote {path}")


def write_add_asm(bits: int, limbs: int, asm_body: str, unroll_body: str) -> None:
    path = ADD_MOD / f"add_mod_asm_{bits}b.cl"
    path.write_text(
        f"{HEADER}{asm_body}{unroll_body}{emit_add_asm_wrapper(bits)}",
        encoding="utf-8",
    )
    print(f"Wrote {path}")


def write_sub_asm(bits: int, limbs: int, asm_body: str, unroll_body: str) -> None:
    path = SUB_MOD / f"sub_mod_asm_{bits}b.cl"
    path.write_text(
        f"{HEADER}{asm_body}{unroll_body}{emit_sub_asm_wrapper(bits)}",
        encoding="utf-8",
    )
    print(f"Wrote {path}")


def main() -> None:
    # 1. Write shared asm common infrastructure
    write_asm_common()

    # 2. Write per-bit unroll files
    for bits, limbs, _max_n in WIDTHS:
        write_add_unroll(bits, emit_add_unroll(limbs, bits))
        write_sub_unroll(bits, emit_sub_unroll(limbs, bits))

    # 3. Write per-bit asm files (no common code; only bodies + wrappers)
    for bits, limbs, _max_n in WIDTHS:
        write_add_asm(bits, limbs, emit_add_asm_body(limbs, bits), emit_add_unroll(limbs, bits))
        write_sub_asm(bits, limbs, emit_sub_asm_body(limbs, bits), emit_sub_unroll(limbs, bits))


if __name__ == "__main__":
    main()
