#!/usr/bin/env python3
"""Generate stage1 Montgomery mul/sqr unrolled kernels (auto loop + manual straight-line).

For each width: A active 32-bit limbs inside a C-limb container (zero-fill A..C-1).
 - auto:   #pragma unroll loops  -> mont_mul/mont_mul_unroll_<W>b.cl        (desktop/non-Android)
 - manual: constant-index form   -> mont_mul/mont_mul_unroll_manual_<W>b.cl (Android; Adreno reg-promotes)
Both are CIOS Montgomery multiply, bit-exact (verified against a bignum reference).
"""
import os, sys
WIDTHS = [(192,6,16),(256,8,16),(384,12,16),(512,16,16),(768,24,24),(1024,32,32)]
ROOT = sys.argv[1] if len(sys.argv)>1 else "kernels/opencl/mont_mul"

def body(stem, A, C, manual):
    mul = f"mont_mul_{stem}"; sqr = f"mont_sqr_{stem}"
    L=[]
    if manual:
        L.append(f"// Stage1 Montgomery mul/sqr - {A*32 if C==A else 'N'}<= {A} active limbs in {C}-limb container.")
        L.append("// Manual constant-index straight-line unroll (mobile GPUs register-promote t[]/B[]/D[]).")
        L.append("// AUTO-GENERATED by tools/gen_mont_unroll.py - do not edit.")
        L.append(f"static inline void {mul}(uint *out, const uint *a, const uint *b, const uint *N, uint np0, uint limbs) {{")
        L.append(f"    uint t[{A+2}];")
        L.append("    " + " ".join(f"t[{k}]=0u;" for k in range(A+2)))
        L.append(f"    uint B[{C}];")
        L.append("    " + " ".join(f"B[{j}]=b[{j}];" for j in range(C)))
        for i in range(A):
            L.append("    {")
            L.append(f"        uint ai=a[{i}]; ulong carry=0ul; ulong uv;")
            for j in range(A):
                L.append(f"        uv=(ulong)t[{j}]+(ulong)ai*(ulong)B[{j}]+carry; t[{j}]=(uint)uv; carry=uv>>32;")
            L.append(f"        ulong top=(ulong)t[{A}]+carry; t[{A}]=(uint)top; t[{A+1}]=(uint)(top>>32);")
            L.append("        uint m=(uint)((ulong)t[0]*(ulong)np0); carry=0ul;")
            for j in range(A):
                st=f" t[{j-1}]=(uint)uv;" if j>0 else ""
                L.append(f"        uv=(ulong)t[{j}]+(ulong)m*(ulong)N[{j}]+carry;{st} carry=uv>>32;")
            L.append(f"        top=(ulong)t[{A}]+carry; t[{A-1}]=(uint)top; top=(ulong)t[{A+1}]+(top>>32); t[{A}]=(uint)top; t[{A+1}]=(uint)(top>>32);")
            L.append("    }")
        L.append(f"    ulong borrow=0ul; uint D[{A}]; ulong w;")
        for i in range(A):
            L.append(f"    w=(ulong)t[{i}]-(ulong)N[{i}]-borrow; D[{i}]=(uint)w; borrow=((ulong)t[{i}]<(ulong)N[{i}]+borrow)?1ul:0ul;")
        L.append(f"    uint need_sub=(t[{A}]|t[{A+1}])!=0u?1u:0u; need_sub=(borrow==0u)?1u:need_sub; uint mask=0u-need_sub;")
        L.append("    " + " ".join(f"out[{i}]=(D[{i}]&mask)|(t[{i}]&~mask);" for i in range(A)))
        if C>A: L.append("    " + " ".join(f"out[{i}]=0u;" for i in range(A,C)))
        L.append("    (void)limbs;")
        L.append("}")
    else:
        pu="    #pragma unroll\n"
        L.append(f"// Stage1 Montgomery mul/sqr - {A} active limbs in {C}-limb container, #pragma-unroll loops.")
        L.append("// AUTO-GENERATED by tools/gen_mont_unroll.py - do not edit.")
        L.append(f"static inline void {mul}(uint *out, const uint *a, const uint *b, const uint *N, uint np0, uint limbs) {{")
        L.append(f"    uint t[{A}u+2u];"); L.append(pu+f"    for (uint i=0u;i<{A}u+2u;++i) t[i]=0u;")
        L.append(f"    uint B[{C}u];"); L.append(pu+f"    for (uint j=0u;j<{C}u;++j) B[j]=b[j];")
        L.append(pu+f"    for (uint i=0u;i<{A}u;++i) {{")
        L.append("        uint ai=a[i]; ulong carry=0ul;")
        L.append(pu+f"        for (uint j=0u;j<{A}u;++j) {{ ulong uv=(ulong)t[j]+(ulong)ai*(ulong)B[j]+carry; t[j]=(uint)uv; carry=uv>>32; }}")
        L.append(f"        ulong top=(ulong)t[{A}u]+carry; t[{A}u]=(uint)top; t[{A}u+1u]=(uint)(top>>32);")
        L.append("        uint m=(uint)((ulong)t[0]*(ulong)np0); carry=0ul;")
        L.append(pu+f"        for (uint j=0u;j<{A}u;++j) {{ ulong uv=(ulong)t[j]+(ulong)m*(ulong)N[j]+carry; if(j>0u) t[j-1u]=(uint)uv; carry=uv>>32; }}")
        L.append(f"        top=(ulong)t[{A}u]+carry; t[{A}u-1u]=(uint)top; top=(ulong)t[{A}u+1u]+(top>>32); t[{A}u]=(uint)top; t[{A}u+1u]=(uint)(top>>32);")
        L.append("    }")
        L.append(f"    ulong borrow=0ul; uint D[{A}u];")
        L.append(pu+f"    for (uint i=0u;i<{A}u;++i) {{ ulong tv=(ulong)t[i],nv=(ulong)N[i]; ulong w=tv-nv-borrow; D[i]=(uint)w; borrow=(tv<nv+borrow)?1ul:0ul; }}")
        L.append(f"    uint need_sub=(t[{A}u]|t[{A}u+1u])!=0u?1u:0u; need_sub=(borrow==0u)?1u:need_sub; uint mask=0u-need_sub;")
        L.append(pu+f"    for (uint i=0u;i<{A}u;++i) out[i]=(D[i]&mask)|(t[i]&~mask);")
        if C>A: L.append(pu+f"    for (uint i={A}u;i<{C}u;++i) out[i]=0u;")
        L.append("    (void)limbs;")
        L.append("}")
    L.append("")
    L.append(f"static inline void {sqr}(uint *out, const uint *a, const uint *N, uint np0, uint limbs) {{")
    L.append(f"    {mul}(out, a, a, N, np0, limbs);")
    L.append("}")
    return "\n".join(L)+"\n"

os.makedirs(ROOT, exist_ok=True)
for (W,A,C) in WIDTHS:
    open(os.path.join(ROOT,f"mont_mul_unroll_{W}b.cl"),"w").write(body(f"unroll_{W}b",A,C,manual=False))
    open(os.path.join(ROOT,f"mont_mul_unroll_manual_{W}b.cl"),"w").write(body(f"unroll_manual_{W}b",A,C,manual=True))
    print(f"wrote {W}b auto+manual (A={A},C={C})")
