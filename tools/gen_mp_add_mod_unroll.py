#!/usr/bin/env python3
"""Generate fully-unrolled mp_add_mod for fixed limb counts (bench only)."""

from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "cgbn/backends/opencl/kernels/mp_addmod_unroll_generated.cl"

HEADER = """// AUTO-GENERATED by tools/gen_mp_add_mod_unroll.py — do not edit.
// Full unroll of fused mp_add_mod (v2+): scalar temps, no inner loops.

"""


def emit_limb_block(i: int) -> str:
    return (
        f"    s = (ulong)a{i} + (ulong)b{i} + ca; ca = s >> 32;\n"
        f"    t = (ulong)(uint)s + (ulong)(~n{i}) + cs; cs = t >> 32; uint r{i} = (uint)t;\n"
    )


def emit_fix_block(i: int) -> str:
    return (
        f"        s = (ulong)r{i} + (ulong)n{i} + c; c = s >> 32; r{i} = (uint)s;\n"
    )


def emit_function(limbs: int) -> str:
    lines = [
        f"inline void mp_add_mod_u{limbs}(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
    ]
    for i in range(limbs):
        lines.append(f"    uint a{i}=a[{i}], b{i}=b[{i}], n{i}=N[{i}];\n")
    lines.append("    ulong ca = 0ul, cs = 1ul, s, t;\n")
    for i in range(limbs):
        lines.append(emit_limb_block(i))
    lines.append("    if (ca == 0ul && cs == 0ul) {\n")
    lines.append("        ulong c = 0ul;\n")
    for i in range(limbs):
        lines.append(emit_fix_block(i))
    lines.append("    }\n")
    for i in range(limbs):
        lines.append(f"    r[{i}] = r{i};\n")
    lines.append("}\n\n")
    return "".join(lines)


def emit_kernel_priv(limbs: int) -> str:
    """Same unroll logic but via x/y/m/r[MAX_LIMBS] like ecm_mp_add_mod_fused."""
    return f"""
#if MAX_LIMBS == {limbs}
__kernel void ecm_mp_add_mod_fused_unroll_priv(
    __global const uint *a,
    __global const uint *b,
    __global const uint *n,
    __global uint *out,
    uint limbs)
{{
    if (limbs != {limbs}u) return;
    uint gid = get_global_id(0);
    uint base = gid * {limbs}u;
    uint x[MAX_LIMBS], y[MAX_LIMBS], m[MAX_LIMBS], r[MAX_LIMBS];
    for (uint i = 0u; i < {limbs}u; ++i) {{
        x[i] = a[base + i];
        y[i] = b[base + i];
        m[i] = n[base + i];
    }}
    mp_add_mod_u{limbs}(r, x, y, m);
    for (uint i = 0u; i < {limbs}u; ++i) {{
        out[base + i] = r[i];
    }}
}}
#endif

"""


def emit_kernel(limbs: int) -> str:
    bits = limbs * 32
    load_a = "".join(f"    uint a{i} = a[base + {i}u];\n" for i in range(limbs))
    load_b = "".join(f"    uint b{i} = b[base + {i}u];\n" for i in range(limbs))
    load_n = "".join(f"    uint n{i} = n[base + {i}u];\n" for i in range(limbs))
    store = "".join(f"    out[base + {i}u] = r{i};\n" for i in range(limbs))

    body = f"""
#if MAX_LIMBS == {limbs}
// Direct global load → scalars → store (no x/y/m/r[MAX_LIMBS] private arrays)
__kernel void ecm_mp_add_mod_fused_unroll(
    __global const uint *a,
    __global const uint *b,
    __global const uint *n,
    __global uint *out,
    uint limbs)
{{
    if (limbs != {limbs}u) return;
    uint gid = get_global_id(0);
    uint base = gid * {limbs}u;
{load_a}{load_b}{load_n}    ulong ca = 0ul, cs = 1ul, s, t;
"""
    for i in range(limbs):
        body += emit_limb_block(i)
    body += """    if (ca == 0ul && cs == 0ul) {
        ulong c = 0ul;
"""
    for i in range(limbs):
        body += emit_fix_block(i)
    body += f"""    }}
{store}}}
#endif

"""
    return body


def main() -> None:
    limb_counts = [64, 128, 256]  # 2048 / 4096 / 8192 bit
    parts = [HEADER]
    for n in limb_counts:
        parts.append(f"// --- {n} limbs ({n * 32} bit) ---\n")
        parts.append(emit_function(n))
    for n in limb_counts:
        parts.append(emit_kernel_priv(n))
    for n in limb_counts:
        parts.append(emit_kernel(n))
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
